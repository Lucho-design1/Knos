//! Toy setup + one proof over the SYNTHETIC sample; writes the fixtures and the program's verifying key.
//!   knos-zk-score <fixtures dir> <vk.rs out>

use ark_bn254::{Bn254, Fr};
use ark_ff::PrimeField;
use ark_groth16::Groth16;
use ark_relations::r1cs::{ConstraintSynthesizer, ConstraintSystem};
use ark_snark::SNARK;
use ark_std::rand::{rngs::StdRng, SeedableRng};
use knos_zk_score::*;
use serde_json::json;
use std::time::Instant;

fn hx<const N: usize>(b: [u8; N]) -> String {
    hex::encode(b)
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let dir = std::path::PathBuf::from(args.get(1).expect("fixtures dir"));
    let vk_rs = std::path::PathBuf::from(args.get(2).expect("vk.rs path"));
    std::fs::create_dir_all(&dir).unwrap();

    let circuit = synthetic_sample(SAMPLE_N, SAMPLE_CORRECT, SAMPLE_THRESHOLD);
    let cs = ConstraintSystem::<Fr>::new_ref();
    circuit.clone().generate_constraints(cs.clone()).unwrap();
    assert!(cs.is_satisfied().unwrap());
    let constraints = cs.num_constraints();

    let mut rng = StdRng::seed_from_u64(TOY_SETUP_SEED);
    let t = Instant::now();
    let (pk, vk) = Groth16::<Bn254>::circuit_specific_setup(circuit.clone(), &mut rng).unwrap();
    let setup_ms = t.elapsed().as_millis();
    let t = Instant::now();
    let proof = Groth16::<Bn254>::prove(&pk, circuit.clone(), &mut rng).unwrap();
    let prove_ms = t.elapsed().as_millis();
    let public = circuit.public_inputs();
    assert!(Groth16::<Bn254>::verify(&vk, &public, &proof).unwrap());

    let w = |name: &str, v: serde_json::Value| {
        std::fs::write(dir.join(name), serde_json::to_string_pretty(&v).unwrap() + "\n").unwrap();
    };
    w(
        "vk.json",
        json!({
            "curve": "bn254", "protocol": "groth16", "encoding": "big-endian; G2 as x.c1,x.c0,y.c1,y.c0 (EIP-197)",
            "setup": "TOY: fixed seed, NOT a ceremony; tests and devnet demo only",
            "alpha_g1": hx(g1_be(&vk.alpha_g1)),
            "beta_g2": hx(g2_be(&vk.beta_g2)),
            "gamma_g2": hx(g2_be(&vk.gamma_g2)),
            "delta_g2": hx(g2_be(&vk.delta_g2)),
            "ic": vk.gamma_abc_g1.iter().map(|p| hx(g1_be(p))).collect::<Vec<_>>(),
        }),
    );
    w(
        "proof.json",
        json!({ "a": hx(g1_be(&proof.a)), "b": hx(g2_be(&proof.b)), "c": hx(g1_be(&proof.c)) }),
    );
    w(
        "public.json",
        json!({
            "names": ["spec_hash", "pred_hash", "threshold"],
            "inputs": public.iter().map(|x| hx(fr_be(x))).collect::<Vec<_>>(),
        }),
    );
    let ints = |v: &Vec<Fr>| v.iter().map(|x| x.into_bigint().0[0]).collect::<Vec<u64>>();
    w(
        "sample.json",
        json!({
            "SYNTHETIC": "made-up labels and predictions from a fixed seed, for tests and the demo; not a real test set",
            "n": SAMPLE_N, "correct": circuit.correct(), "threshold": SAMPLE_THRESHOLD,
            "labels": ints(&circuit.labels), "preds": ints(&circuit.preds),
            "spec_salt": hx(fr_be(&circuit.spec_salt)), "pred_salt": hx(fr_be(&circuit.pred_salt)),
        }),
    );
    w(
        "meta.json",
        json!({
            "constraints": constraints, "public_inputs": public.len(),
            "setup_ms": setup_ms as u64, "prove_ms": prove_ms as u64,
            "measured_on": "WSL2 Ubuntu-24.04, 4 vCPU, 4 GB VM (the founder's build box)",
        }),
    );

    // the verifying key the program embeds, in groth16-solana's struct
    let arr = |b: &[u8]| b.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(",");
    let mut s = String::new();
    s.push_str("// GENERATED by zk/score_circuit (cargo run --release); do not edit. TOY setup (fixed seed): devnet only.\n");
    s.push_str("use groth16_solana::groth16::Groth16Verifyingkey;\n\n");
    s.push_str(&format!("pub const NR_PUBLIC_INPUTS: usize = {};\n\n", public.len()));
    s.push_str("pub const VERIFYINGKEY: Groth16Verifyingkey = Groth16Verifyingkey {\n");
    s.push_str(&format!("    nr_pubinputs: {},\n", public.len()));
    s.push_str(&format!("    vk_alpha_g1: [{}],\n", arr(&g1_be(&vk.alpha_g1))));
    s.push_str(&format!("    vk_beta_g2: [{}],\n", arr(&g2_be(&vk.beta_g2))));
    s.push_str(&format!("    vk_gamme_g2: [{}],\n", arr(&g2_be(&vk.gamma_g2))));
    s.push_str(&format!("    vk_delta_g2: [{}],\n", arr(&g2_be(&vk.delta_g2))));
    s.push_str("    vk_ic: &[\n");
    for p in &vk.gamma_abc_g1 {
        s.push_str(&format!("        [{}],\n", arr(&g1_be(p))));
    }
    s.push_str("    ],\n};\n");
    std::fs::write(&vk_rs, s).unwrap();
    println!("constraints {constraints} setup_ms {setup_ms} prove_ms {prove_ms}");
}
